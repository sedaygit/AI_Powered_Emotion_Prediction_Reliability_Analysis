"""Görüntü özelliklerine göre model değerlendirme (brightness, contrast, blur)"""

import cv2
import zipfile
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from pathlib import Path
from ultralytics import YOLO

# --------------------------------------------------
# 1. Dosya yolları
# --------------------------------------------------

zip_path = "/content/drive/MyDrive/emotions56.zip"
model_path = "/content/emotions56/yolov8n-emo.pt"

