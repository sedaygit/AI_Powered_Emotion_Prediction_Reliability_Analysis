results = model.predict(
    source=image_paths,
    conf=0.001,
    save=False,
    verbose=False
)

predictions = []

for result in results:

    image_name = Path(result.path).name
    label_path = os.path.join(
        test_labels_path,
        Path(image_name).stem + ".txt"
    )

    # Gerçek sınıfı oku
    with open(label_path, "r") as f:
        true_class = int(f.readline().split()[0])

    # Model tahmini
    if result.boxes is not None and len(result.boxes) > 0:

        best_index = result.boxes.conf.argmax()

        predicted_class = int(
            result.boxes.cls[best_index].item()
        )

        confidence = float(
            result.boxes.conf[best_index].item()
        )

    else:
        predicted_class = -1
        confidence = 0.0

    predictions.append({
        "image_name": image_name,
        "true_emotion": model.names[true_class],
        "predicted_emotion": (
            model.names[predicted_class]
            if predicted_class != -1
            else "no_detection"
        ),
        "true_class": true_class,
        "predicted_class": predicted_class,
        "yolo_confidence": confidence,
        "correct": true_class == predicted_class
    })

df = pd.DataFrame(predictions)

