# --------------------------------------------------
# 2. Test verilerini çıkar
# --------------------------------------------------

extract_path.mkdir(parents=True, exist_ok=True)

with zipfile.ZipFile(zip_path, "r") as zip_ref:
    zip_ref.extractall(extract_path)

image_dir = extract_path / "test" / "images"
label_dir = extract_path / "test" / "labels"

# --------------------------------------------------
# 3. Mevcut YOLO modelini yükle
# --------------------------------------------------

model = YOLO(model_path)

print("Model sınıfları:", model.names)

# --------------------------------------------------
# 4. Görüntüleri ve özellikleri incele
# --------------------------------------------------

records = []

image_paths = sorted(image_dir.glob("*.png"))

for image_path in image_paths:

    label_path = label_dir / f"{image_path.stem}.txt"

    if not label_path.exists():
        print("Etiket bulunamadı:", image_path.name)
        continue

    # Gerçek sınıfı oku
    label_values = label_path.read_text().strip().split()

    if not label_values:
        print("Boş etiket:", image_path.name)
        continue

    true_class = int(label_values[0])

    # Görüntüyü oku
    image = cv2.imread(str(image_path))

    if image is None:
        print("Görüntü okunamadı:", image_path.name)
        continue

    height, width = image.shape[:2]
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    # Görüntü özellikleri
    brightness = float(np.mean(gray))
    contrast = float(np.std(gray))
    blur = float(cv2.Laplacian(
        gray, cv2.CV_64F
    ).var())

    # YOLO tahmini
    result = model.predict(
        source=image,
        conf=0.001,
        iou=0.7,
        verbose=False
    )[0]

    if result.boxes is not None and len(result.boxes) > 0:

        best_index = result.boxes.conf.argmax()

        predicted_class = int(
            result.boxes.cls[best_index].item()
        )

        confidence = float(
            result.boxes.conf[best_index].item()
        )

        # Tahmin edilen yüzün görüntü alanına oranı
        x1, y1, x2, y2 = result.boxes.xyxy[
            best_index
        ].cpu().numpy()

        face_area = max(0, x2 - x1) * max(0, y2 - y1)
        face_size = float(face_area / (width * height))

    else:
        predicted_class = -1
        confidence = 0.0
        face_size = 0.0

    # Tahmin doğru mu?
    error_risk = int(predicted_class != true_class)

    records.append({
        "image": image_path.name,
        "brightness": brightness,
        "blur": blur,
        "contrast": contrast,
        "face_size": face_size,
        "confidence": confidence,
        "predicted_class": predicted_class,
        "true_class": true_class,
        "error_risk": error_risk
    })

# --------------------------------------------------
# 5. DataFrame oluştur ve kaydet
# --------------------------------------------------

df = pd.DataFrame(records)

output_path = "/content/emotion_error_analysis.csv"

df.to_csv(output_path, index=False)

