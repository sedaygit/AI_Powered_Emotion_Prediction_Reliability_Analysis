def predict_emotion_and_risk(image_path):

    # Görüntüyü oku
    image = cv2.imread(image_path)

    if image is None:
        raise ValueError("Görüntü okunamadı!")

    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    # Görüntü özelliklerini hesapla
    brightness = float(np.mean(gray))
    contrast = float(np.std(gray))
    blur = float(cv2.Laplacian(gray, cv2.CV_64F).var())

    height, width = image.shape[:2]

    # YOLO tahmini
    results = yolo_model.predict(
        source=image,
        conf=0.001,
        iou=0.7,
        verbose=False
    )

    boxes = results[0].boxes

    # En yüksek confidence değerine sahip kutuyu al
    if boxes is not None and len(boxes) > 0:

        best_index = int(boxes.conf.argmax())

        confidence = float(boxes.conf[best_index])
        predicted_class = int(boxes.cls[best_index])

        x1, y1, x2, y2 = boxes.xyxy[best_index].cpu().numpy()

        face_size = float(
            ((x2 - x1) * (y2 - y1)) / (width * height)
        )

    else:
        print("YOLO görüntüde yüz tespit edemedi.")
        return

    # İkinci modelin beklediği özellikler
    features = pd.DataFrame([{
        "brightness": brightness,
        "blur": blur,
        "contrast": contrast,
        "face_size": face_size,
        "confidence": confidence,
        "predicted_class": predicted_class
    }])

    # Hata riski tahmini
    risk_prediction = int(error_model.predict(features)[0])

    # Tahmin olasılıkları
    probabilities = error_model.predict_proba(features)[0]
    risk_probability = float(probabilities[1])

    # Sonuçları göster
    print("\n========== TAHMİN SONUCU ==========")
    print("YOLO duygu tahmini:", class_names[predicted_class])
    print("YOLO confidence:", round(confidence, 4))

    print("\nGörüntü özellikleri:")
    print("Brightness:", round(brightness, 2))
    print("Blur:", round(blur, 2))
    print("Contrast:", round(contrast, 2))
    print("Face size:", round(face_size, 4))

    print("\nİKİNCİ MODEL SONUCU:")

    if risk_prediction == 1:
        print("Hata riski: YÜKSEK")
    else:
        print("Hata riski: DÜŞÜK")

    print("Tahmin edilen hata olasılığı:",
          f"%{risk_probability * 100:.2f}")

    display(features)

