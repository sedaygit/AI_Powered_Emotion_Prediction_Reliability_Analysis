import zipfile
import os
from collections import Counter

zip_path = "/content/drive/MyDrive/emotions56.zip"

class_names = {
    0: "anger",
    1: "contempt",
    2: "disgust",
    3: "fear",
    4: "happiness",
    5: "neutrality",
    6: "sadness",
    7: "surprise"
}

with zipfile.ZipFile(zip_path, "r") as z:

    files = z.namelist()

    test_images = [
        f for f in files
        if f.startswith("test/images/")
        and f.lower().endswith((".png", ".jpg", ".jpeg"))
    ]

    test_labels = [
        f for f in files
        if f.startswith("test/labels/")
        and f.lower().endswith(".txt")
    ]

    image_names = {
        os.path.splitext(os.path.basename(f))[0]
        for f in test_images
    }

    label_names = {
        os.path.splitext(os.path.basename(f))[0]
        for f in test_labels
    }

    print("TEST VERİ SETİ")
    print("-" * 40)

    print("Görüntü sayısı:", len(test_images))
    print("Etiket sayısı:", len(test_labels))

    print("\nEtiketi eksik görüntüler:")
    print(image_names - label_names)

    print("\nGörüntüsü eksik etiketler:")
    print(label_names - image_names)

    classes = Counter()
    invalid_labels = []
    box_counts = Counter()

    for label_file in test_labels:

        content = z.read(label_file).decode("utf-8").strip()

        if not content:
            invalid_labels.append(label_file)
            continue

        lines = content.splitlines()
        box_counts[len(lines)] += 1

        for line in lines:

            values = line.split()

            if len(values) != 5:
                invalid_labels.append(label_file)
                continue

            class_id = int(float(values[0]))

            if class_id not in class_names:
                invalid_labels.append(label_file)
                continue

            classes[class_id] += 1

    print("\nSINIF DAĞILIMI")
    print("-" * 40)

    for class_id, name in class_names.items():
        print(f"{name}: {classes[class_id]}")

    print("\nBounding box sayıları:", dict(box_counts))
    print("Hatalı etiket dosyaları:", invalid_labels)

    print("\nEşleşme kontrolü:",
          "BAŞARILI" if image_names == label_names else "HATALI")

